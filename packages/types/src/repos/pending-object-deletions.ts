// ── Pending object-deletion records used by PendingObjectDeletionsRepo ──
//
// The transactional outbox for object-storage (R2/S3) deletes. A row captures
// the *intent* to delete a single key or an entire prefix, written in the same
// DB transaction as the owning row's cascade, then drained by a scheduled job.

/** Whether `targetKey` is an exact object key or a prefix to list-and-delete. */
export type PendingObjectDeletionKind = "KEY" | "PREFIX";

/**
 * Lifecycle status. Validated in app code (not a Prisma enum):
 * - "PENDING" → eligible for the drain job.
 * - "DEAD"    → exhausted maxAttempts; left for manual inspection.
 */
export type PendingObjectDeletionStatus = "PENDING" | "DEAD";

/** Mirrors the `PendingObjectDeletion` Prisma model. */
export interface PendingObjectDeletionRecord {
  id: string;
  targetKey: string;
  targetKind: PendingObjectDeletionKind;
  status: PendingObjectDeletionStatus;
  attempts: number;
  lastError: string | null;
  nextAttemptAt: Date;
  source: string | null;
  sourceId: string | null;
  createdAt: Date;
  updatedAt: Date;
}

/** A single delete intent to enqueue. */
export interface EnqueuePendingObjectDeletionItem {
  /**
   * Row id, when the caller needs to find the row again (e.g. to remove an
   * intent it then fulfilled itself). Omitted = generated by the database.
   */
  id?: string;
  targetKey: string;
  targetKind: PendingObjectDeletionKind;
  source?: string;
  sourceId?: string;
  /**
   * Earliest time the drain may attempt it (its first `nextAttemptAt`).
   * Omitted = due immediately. Used to delete an upload key again after its
   * presigned PUT URL has expired, catching a re-PUT made after finalize.
   */
  notBefore?: Date;
}

/**
 * An intent enqueued at most once: the caller picks the row id, and a second
 * enqueue with the same id leaves the first row as it is.
 */
export type EnqueuePendingObjectDeletionOnceItem = EnqueuePendingObjectDeletionItem & {
  id: string;
};

/**
 * What {@link EnqueuePendingObjectDeletionOnceItem} did. When the id was
 * taken, `existing` is the row that holds it (null if it was drained in
 * between).
 */
export type EnqueuePendingObjectDeletionOnceResult =
  | { inserted: true }
  | { inserted: false; existing: PendingObjectDeletionRecord | null };

export interface ListDuePendingObjectDeletionsInput {
  now: Date;
  limit: number;
}

export interface MarkPendingObjectDeletionFailedInput {
  id: string;
  lastError: string;
  nextAttemptAt: Date;
}

export interface MarkPendingObjectDeletionDeadInput {
  id: string;
  lastError: string;
}

/**
 * Selection for the outbox-health count.
 *
 * ABSOLUTE instant, caller-computed — same convention as
 * `CountModerationQueueHealthInput` in the moderation repo. The repo does no
 * clock arithmetic, so "overdue" means exactly one thing and the surface that
 * displays it can label itself from the number it passed in.
 */
export interface CountPendingObjectDeletionsInput {
  /**
   * A PENDING row still undrained at this instant is OVERDUE.
   *
   * Callers MUST pass a cutoff in the PAST, not `now`. Every freshly enqueued
   * row has `nextAttemptAt = now()` and is therefore due immediately; measuring
   * against `now` would count normal in-flight work as a stalled outbox and
   * make the number useless on its busiest days.
   */
  dueBefore: Date;
  /**
   * Restrict to rows enqueued by ONE producer (the `source` column), or count
   * the whole outbox when omitted.
   *
   * The moderation ops surface passes `"image-moderation-reject"` — the string
   * `review-flagged-image.ts` stamps when a REJECT decision enqueues the R2
   * object — so its tile is genuinely "images we told an uploader we removed",
   * not "everything anyone ever queued for deletion".
   */
  source?: string;
}

/**
 * Two counts, deliberately not summed: they call for different responses.
 *
 * A DEAD row will never be retried by anything — the bytes stay live until a
 * human intervenes. An OVERDUE row means the drain itself is not running, which
 * is an incident affecting every producer at once. Adding them together would
 * produce a number that is actionable in neither direction.
 */
export interface PendingObjectDeletionOutboxHealth {
  /**
   * `status = "DEAD"` — exhausted its attempt budget, left for manual
   * inspection, and touched by no automation ever again.
   */
  dead: number;
  /**
   * `status = "PENDING"` and due before the caller's cutoff.
   *
   * "Still undeleted" is implicit rather than a clause: `markDeleted` HARD
   * DELETES the row on success, so the existence of a row IS the undeleted
   * condition. If that ever becomes a soft delete, this count silently starts
   * including drained rows — add the clause then.
   */
  overdue: number;
}

/**
 * Withdraw delete intents a producer queued for keys that are in use again
 * (page editor: an image a discarded draft held, put back by a later save).
 * Only PENDING rows of `source` whose targetKey is listed; DEAD rows and other
 * producers' rows are never touched.
 */
export interface CancelPendingObjectDeletionsInput {
  source: string;
  targetKeys: readonly string[];
}
