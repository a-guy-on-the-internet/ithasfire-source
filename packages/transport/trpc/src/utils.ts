const toUseCaseError = (err: unknown): UseCaseError | null => {
  if (!err || typeof err !== "object") return null;
  if (!("code" in err) || typeof (err as any).code !== "string") return null;
  return err as UseCaseError;
};

/**
 * Resolve the canonical {@link AppErrorCode} for a use-case error.
 *
 * The use-case `code` is normally a transport CATEGORY (`not_found`,
 * `forbidden`, …) and the `message` carries the snake_case DOMAIN code
 * (`event_not_found`, `agreement_not_draft`). For a handful of errors the
 * `code` field itself is the domain code (e.g. `event_already_has_agreement`).
 *
 * Resolution order: an explicit `AppError` instance wins. Otherwise the
 * `message` is the canonical domain code and is tried first — but ONLY because
 * the `code` field is usually a transport CATEGORY (`not_found`, `forbidden`),
 * which is itself a valid `AppErrorCode` and would otherwise mask the more
 * specific domain code in `message` (e.g. `{ code: "not_found", message:
 * "event_not_found" }` must resolve to `EVENT_NOT_FOUND`, not `NOT_FOUND`).
 * When the `message` doesn't resolve we fall back to the `code` field, which
 * covers the cases where the domain code lives there directly (e.g.
 * `event_already_has_agreement`). Returns `null` for unmapped / internal
 * errors — callers treat that as "no stable code".
 *
 * Trying `message` first is safe even when it's a free-text human sentence:
 * `fromLegacyCode` upper-cases the whole string and does an exact Set lookup
 * (no tokenization), so a sentence never accidentally matches a code — it
 * returns `null` and we fall through to the `code` field.
 */
const resolveAppCode = (
  err: unknown,
  useCaseErr: UseCaseError,
): AppErrorCode | null => {
  if (isAppError(err)) return err.code;
  return (
    (useCaseErr.message ? fromLegacyCode(useCaseErr.message) : null) ??
    fromLegacyCode(useCaseErr.code)
  );
};

/**
 * Marks a TRPCError whose `.meta` was curated by a use case via
 * `fail(code, { meta })` / `new AppError(...)`. The production 500 scrub keeps
 * that meta (e.g. the dispute desk reads `meta.processorError` off a
 * DISPUTE_EVIDENCE_SUBMIT_FAILED) but drops every other meta bag — an adapter
 * error such as Prisma's carries raw DB text on its own `.meta`.
 */
const CURATED_META = Symbol.for("th.trpc.curatedMeta");

/**
 * Domain meta that is safe on the wire even for a production 500: only meta a
 * use case curated on an AppError. `undefined` for anything else.
 */
export const readCuratedDomainMeta = (
  error: unknown,
): Record<string, unknown> | undefined => {
  if (!error || typeof error !== "object") return undefined;
  if ((error as Record<symbol, unknown>)[CURATED_META] === true) {
    return readDomainMeta(error);
  }
  // A TRPCError built elsewhere around an AppError cause.
  const cause = (error as { cause?: unknown }).cause;
  if (isAppError(cause) && cause.meta) {
    return { ...cause.meta, appCode: cause.code };
  }
  return undefined;
};

/**
 * Codes whose wire `data.meta` must carry NOTHING but `appCode`, whatever a
 * thrower attaches. They are refusals the SENDER sees on "Agree & book"
 * (booking-the-night FR-001): an act sees only its own place in a line
 * (booking-holds FR-013), so another party's hold, line, calendar or event
 * must never reach it — not even by a future `fail(..., { meta })` slip.
 *   - NIGHT_NO_LONGER_AVAILABLE — the night went to someone else;
 *   - BOOKING_ALREADY_HAS_NIGHT — this request booked another night;
 *   - TERMS_CHANGED_SINCE_VIEWED — the terms moved after the sender read them;
 *   - EVENT_ON_ANOTHER_NIGHT — the booking's event is on another day;
 *   - EVENT_FIRST_ORIGIN_GONE — an event-first request's origin event was
 *     cancelled or archived;
 *   - LINKED_EVENT_NOT_LIVE — the event the terms were finalized against was
 *     cancelled or archived;
 *   - PLACE_NOT_TAKING_BOOKINGS — the place is suspended or retired;
 *   - BOOKING_CANCELLED — the request's booking was cancelled (P2c);
 *   - BOOKING_NIGHT_BOOKED — withdraw refused, the night is booked (P2c).
 * Venue-side codes that carry meta by design (NIGHT_TAKEN,
 * HOLD_DATE_MISMATCHES_EVENT, TERMS_SENT_FOR_ANOTHER_NIGHT,
 * TERMS_AGREED_FOR_ANOTHER_NIGHT, PLACE_NOT_ACTIVE, INVALID_STATUS) are NOT
 * listed.
 * The use case's message is dropped too (the code's own name goes out), so
 * free text cannot smuggle it either.
 */
export const META_FREE_APP_CODES: ReadonlySet<AppErrorCode> = new Set<
  AppErrorCode
>([
  "NIGHT_NO_LONGER_AVAILABLE",
  "BOOKING_ALREADY_HAS_NIGHT",
  "TERMS_CHANGED_SINCE_VIEWED",
  "EVENT_ON_ANOTHER_NIGHT",
  "EVENT_FIRST_ORIGIN_GONE",
  "LINKED_EVENT_NOT_LIVE",
  "PLACE_NOT_TAKING_BOOKINGS",
  "BOOKING_CANCELLED",
  "BOOKING_NIGHT_BOOKED",
]);

export const toTrpcError = (err: unknown): TRPCError => {
  if (err instanceof TRPCError) return err;

  // Structured AppError (the preferred shape for new code). Resolve the tRPC
  // status from the canonical code — borrowing the optional `category` hint's
  // bucket first — and surface `data.appCode` directly from `err.code` instead
  // of the message-first/code-fallback guessing the legacy path needs. The
  // legacy `{ code, message }` path below is left byte-for-byte unchanged.
  if (isAppError(err)) {
    const trpcCode =
      appCodeToTrpc[err.category ?? err.code] ?? "INTERNAL_SERVER_ERROR";
    const metaFree = META_FREE_APP_CODES.has(err.code);
    const trpcError = new TRPCError({
      code: trpcCode,
      message: metaFree ? err.code : err.message,
      // Keep the underlying cause for Sentry's `linkedErrors`; fall back to the
      // AppError itself (it is a real Error with a stack) when none was given.
      cause: err.cause ?? err,
    });
    (trpcError as TRPCError & { meta?: Record<string, unknown> }).meta = {
      ...(metaFree ? {} : (err.meta ?? {})),
      appCode: err.code,
    };
    Object.defineProperty(trpcError, CURATED_META, { value: true });
    return trpcError;
  }

  const useCaseErr = toUseCaseError(err);
  if (useCaseErr) {
    const trpcCode =
      errorCodeMap[useCaseErr.code as keyof typeof errorCodeMap] ??
      "INTERNAL_SERVER_ERROR";
    const appCode = resolveAppCode(err, useCaseErr);
    // The errorFormatter (packages/transport/trpc/src/trpc.ts) surfaces client-facing
    // detail by reading `error.cause.meta`. We keep `cause` pointed at the
    // original SDK/adapter error (or the synthetic use-case object) so Sentry's
    // `linkedErrors` integration still walks the real failure — we do NOT
    // replace the cause chain. Instead we stash the merged meta (existing
    // domain meta + the resolved `appCode`) on a `meta` property of the
    // TRPCError itself, and the formatter reads `error.cause.meta ?? error.meta`.
    const metaFree = appCode !== null && META_FREE_APP_CODES.has(appCode);
    const trpcError = new TRPCError({
      code: trpcCode,
      message: metaFree ? appCode : (useCaseErr.message ?? useCaseErr.code),
      // Prefer the underlying SDK / adapter error when the use-case
      // attached one — Sentry's `linkedErrors` only walks `Error`
      // instances, so the synthetic `{ code, message }` wrapper would
      // otherwise terminate the cause chain.
      cause: useCaseErr.cause ?? err,
    });
    const mergedMeta = {
      ...(metaFree ? {} : (useCaseErr.meta ?? {})),
      ...(appCode ? { appCode } : {}),
    };
    if (Object.keys(mergedMeta).length > 0) {
      // Non-cause channel for the formatter; preserves the Sentry cause chain.
      (trpcError as TRPCError & { meta?: Record<string, unknown> }).meta =
        mergedMeta;
    }
    return trpcError;
  }
  // ZodError has no top-level `.code`, so it falls through the checks above.
  // Its `.message` is `JSON.stringify(issues, null, 2)` (Zod v4) — the raw
  // validation issue dump. By the time a bare `.parse()` throws all the way
  // out to here, it's almost always output-schema validation (input already
  // went through parseInput/toUseCaseError above), i.e. a server-side
  // data/schema-integrity bug — not something to hand to the client. Keep a
  // clean generic wire message and stash the real ZodError on `cause` so
  // Sentry/logging still see the actual issues.
  if (err instanceof ZodError) {
    return new TRPCError({
      code: "INTERNAL_SERVER_ERROR",
      message: "Internal validation error",
      cause: err,
    });
  }
  if (err instanceof Error) {
    return new TRPCError({
      code: "INTERNAL_SERVER_ERROR",
      message: err.message,
      cause: err,
    });
  }
  return new TRPCError({
    code: "INTERNAL_SERVER_ERROR",
    message: "Unknown error",
    cause: err as any,
  });
};

/**
 * Read the domain `meta` bag off a tRPC error for the wire response.
 * `toTrpcError` stashes the merged domain meta (existing domain meta + the
 * resolved `appCode`) directly on the TRPCError instance's `.meta`; older /
 * direct TRPCErrors carry it on `.cause.meta`. Read both, preferring the
 * direct `.meta`. Returns `undefined` when neither is an object so the
 * errorFormatter can omit `data.meta` entirely (e.g. Zod input errors).
 */
export const readDomainMeta = (
  error: unknown,
): Record<string, unknown> | undefined => {
  const e = (error ?? {}) as { meta?: unknown; cause?: unknown };
  const direct =
    e.meta && typeof e.meta === "object"
      ? (e.meta as Record<string, unknown>)
      : undefined;
  if (direct) return direct;
  const cause = e.cause;
  const causeMeta =
    cause && typeof cause === "object" && "meta" in cause
      ? (cause as { meta?: unknown }).meta
      : undefined;
  return causeMeta && typeof causeMeta === "object"
    ? (causeMeta as Record<string, unknown>)
    : undefined;
};

/**
 * Resolve the stable, machine-readable {@link AppErrorCode} for a tRPC error
 * (FR-002) for the wire response (errorFormatter) and the server log line
 * (apps/api `onError`) — a single source of truth so the two can never
 * disagree (FR-008). Prefers the code resolved at conversion time —
 * `toTrpcError` stashes it on `error.meta.appCode`, while older / direct
 * TRPCErrors carry it on `error.cause.meta.appCode` — then falls back to the
 * canonical code off an `AppError` on `error` or `error.cause`, and finally to
 * deriving it from the snake_case message. Returns `null` for unmapped /
 * internal errors (e.g. Zod input-validation errors, which never carry a
 * domain code).
 *
 * We deliberately DO NOT read `error.code` on a non-`AppError` (the outer
 * TRPCError): its `.code` is the transport bucket (`PRECONDITION_FAILED`, …),
 * which is itself a valid `AppErrorCode` and would mask the more specific
 * domain code carried on `.cause`.
 */
export const resolveWireAppCode = (error: unknown): string | null => {
  const metaFrom = (m: unknown): string | undefined =>
    m &&
    typeof m === "object" &&
    typeof (m as { appCode?: unknown }).appCode === "string"
      ? (m as { appCode: string }).appCode
      : undefined;
  // Canonical code off an AppError instance only. `fromLegacyCode` doubles as
  // the validator: it returns the code unchanged when it is a known
  // `AppErrorCode`, else `null`.
  const appCodeFrom = (e: unknown): string | undefined => {
    if (!isAppError(e)) return undefined;
    return fromLegacyCode(e.code) ?? undefined;
  };
  const e = (error ?? {}) as {
    meta?: unknown;
    cause?: { meta?: unknown } | unknown;
    message?: unknown;
  };
  return (
    metaFrom(e.meta) ??
    metaFrom((e.cause as { meta?: unknown } | undefined)?.meta) ??
    appCodeFrom(error) ??
    appCodeFrom(e.cause) ??
    (typeof e.message === "string" ? fromLegacyCode(e.message) : null) ??
    null
  );
};

