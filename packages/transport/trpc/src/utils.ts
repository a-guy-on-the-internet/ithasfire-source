/**
 * Whether a canonical {@link AppErrorCode} maps to the `INTERNAL_SERVER_ERROR`
 * (500) tRPC bucket — i.e. a genuine server fault, not an expected client /
 * precondition error.
 *
 * The Sentry `beforeSend` backstop (apps/api/src/instrument.ts) uses this to
 * decide whether an `AppError`-shaped event is worth a Sentry issue: expected
 * non-500 domain errors (a 404/409/412/…) are dropped, real 500s are kept.
 *
 * An UNRECOGNIZED code (not present in {@link appCodeToTrpc}) is treated as
 * internal (`true`) so we never silently hide a genuinely-unknown failure.
 */
export const isInternalAppCode = (code: string): boolean => {
  const bucket = appCodeToTrpc[code as AppErrorCode];
  // Unknown code → assume internal (keep the Sentry event) to avoid hiding bugs.
  if (!bucket) return true;
  return bucket === "INTERNAL_SERVER_ERROR";
};

