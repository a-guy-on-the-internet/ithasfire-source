import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { DEFAULT_LOCALE, SUPPORTED_LOCALES } from "@th/locale";
import { listTemplates, render, sampleInputFor } from "../src";
import type { TemplateId } from "../src";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(scriptDir, "..");
const repoRoot = resolve(packageRoot, "../..");
const targetRelativePath = "packages/ui/src/stories/email/generated/samples.ts";
const targetPath = resolve(repoRoot, targetRelativePath);

const toDisplayName = (id: TemplateId) =>
  id
    .split(".")
    .map((segment) =>
      segment
        .split("_")
        .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
        .join(" "),
    )
    .join(" · ");

async function main() {
  const summaries = listTemplates();
  const buildTimestamp = new Date().toISOString();

  const samples = [] as Array<{
    id: TemplateId;
    displayName: string;
    subject: string;
    html: string;
    text: string;
    props: unknown;
    requiredProps: string[];
    hasTextTemplate: boolean;
    variants: Array<{
      locale: string;
      subject: string;
      html: string;
      text: string;
    }>;
  }>;

  for (const summary of summaries) {
    const props = sampleInputFor(summary.id);
    const variants: Array<{
      locale: string;
      subject: string;
      html: string;
      text: string;
    }> = [];

    for (const locale of SUPPORTED_LOCALES) {
      const result = await render({ templateId: summary.id, props, locale });
      variants.push({
        locale,
        subject: result.subject,
        html: result.html,
        text: result.text,
      });
    }

    const defaultVariant = variants.find(
      (variant) => variant.locale === DEFAULT_LOCALE,
    ) ??
      variants[0] ?? {
        locale: DEFAULT_LOCALE,
        subject: "",
        html: "",
        text: "",
      };

    samples.push({
      id: summary.id,
      displayName: toDisplayName(summary.id),
      subject: defaultVariant.subject,
      html: defaultVariant.html,
      text: defaultVariant.text,
      props,
      requiredProps: summary.requiredProps,
      hasTextTemplate: summary.hasTextTemplate,
      variants,
    });
  }

  samples.sort((a, b) => a.displayName.localeCompare(b.displayName));

  const serialized = JSON.stringify(samples, null, 2);

  const fileContents = `/* eslint-disable */\n// @generated by packages/ui-email/scripts/generate-storybook-data.ts\n// Run \`pnpm -F @th/ui-email storybook:samples\` to refresh.\nimport type { TemplateId } from "@th/ui-email";\n\nexport type EmailStorybookVariant = {\n\tlocale: string;\n\tsubject: string;\n\thtml: string;\n\ttext: string;\n};\n\nexport type EmailStorybookSample = {\n\tid: TemplateId;\n\tdisplayName: string;\n\tsubject: string;\n\thtml: string;\n\ttext: string;\n\tprops: Record<string, unknown>;\n\trequiredProps: string[];\n\thasTextTemplate: boolean;\n\tvariants: EmailStorybookVariant[];\n};\n\nexport const emailStorybookNotice = "";\n\nexport const emailStorybookSamples: EmailStorybookSample[] = ${serialized} as EmailStorybookSample[];\n\nexport const emailStorybookSampleMap = Object.fromEntries(\n\temailStorybookSamples.map((sample) => [sample.id, sample] as const),\n) as Record<TemplateId, EmailStorybookSample>;\n\nexport const emailStorybookGeneratedAt = "${buildTimestamp}";\n`;

  await mkdir(dirname(targetPath), { recursive: true });
  await writeFile(targetPath, fileContents, "utf8");

  process.stdout.write(`✔︎ Wrote Storybook samples to ${targetRelativePath}\n`);
}

main().catch((error) => {
  const message = error instanceof Error ? error.message : String(error);
  const stack = error instanceof Error && error.stack ? `\n${error.stack}` : "";
  const details =
    error && typeof error === "object" && "details" in error
      ? `\nDetails: ${JSON.stringify((error as { details?: unknown }).details, null, 2)}`
      : "";
  process.stderr.write(
    `Failed to generate Storybook samples: ${message}${details}${stack}\n`,
  );
  process.exit(1);
});
