#!/usr/bin/env bash
# ──────────────────────────────────────────────────────────────────────
# scripts/dev/sentry-setup.sh
#
# Bootstraps Sentry env vars for local development.
#
# Prerequisites:
#   brew install getsentry/tools/sentry-cli
#   export SENTRY_AUTH_TOKEN=sntrys_...   (in your .zshrc)
#
# Usage:
#   ./scripts/dev/sentry-setup.sh
#
# What it does:
#   1. Verifies sentry-cli is installed and authenticated
#   2. Fetches the DSN for hearth-fire-web (used by both web + API)
#   3. Writes SENTRY_DSN / NEXT_PUBLIC_SENTRY_DSN into:
#        - .env.local  (root, shared)
#        - apps/web/.env.sentry-build-plugin  (source map upload token)
#   4. Sets SENTRY_ENVIRONMENT=development so errors are tagged correctly
# ──────────────────────────────────────────────────────────────────────
set -euo pipefail

SENTRY_ORG="hearth-fire"
SENTRY_PROJECT="hearth-fire-web"

RED='\033[0;31m'
GREEN='\033[0;32m'
CYAN='\033[0;36m'
DIM='\033[2m'
RESET='\033[0m'

info()  { printf "${CYAN}▸${RESET} %s\n" "$1"; }
ok()    { printf "${GREEN}✓${RESET} %s\n" "$1"; }
fail()  { printf "${RED}✗${RESET} %s\n" "$1" >&2; exit 1; }

# ── 1. Check sentry-cli ─────────────────────────────────────────────
if ! command -v sentry-cli &>/dev/null; then
  fail "sentry-cli not found. Install with:  brew install getsentry/tools/sentry-cli"
fi
ok "sentry-cli found: $(sentry-cli --version)"

# ── 2. Check auth token ─────────────────────────────────────────────
if [[ -z "${SENTRY_AUTH_TOKEN:-}" ]]; then
  fail "SENTRY_AUTH_TOKEN is not set. Add to your .zshrc:\n  export SENTRY_AUTH_TOKEN=sntrys_..."
fi

# Verify the token works
info "Verifying Sentry auth..."
if ! sentry-cli info --no-defaults 2>/dev/null | grep -q "Auth Token"; then
  fail "Auth token is invalid or expired. Generate a new one at:\n  https://sentry.io/settings/auth-tokens/"
fi
ok "Authenticated to Sentry"

# ── 3. Fetch DSN via API ────────────────────────────────────────────
info "Fetching DSN for ${SENTRY_ORG}/${SENTRY_PROJECT}..."

DSN_JSON=$(curl -sS \
  -H "Authorization: Bearer ${SENTRY_AUTH_TOKEN}" \
  "https://sentry.io/api/0/projects/${SENTRY_ORG}/${SENTRY_PROJECT}/keys/")

# Extract the public DSN from the first active key
DSN=$(echo "$DSN_JSON" | python3 -c "
import json, sys
keys = json.load(sys.stdin)
for k in keys:
    if k.get('isActive'):
        print(k['dsn']['public'])
        break
" 2>/dev/null || true)

if [[ -z "$DSN" ]]; then
  echo ""
  echo "Could not retrieve DSN. Possible causes:"
  echo "  • Project '${SENTRY_PROJECT}' doesn't exist in org '${SENTRY_ORG}'"
  echo "  • Your auth token lacks the 'project:read' scope"
  echo ""
  echo "To create the project, visit:"
  echo "  https://sentry.io/organizations/${SENTRY_ORG}/projects/new/"
  echo ""
  echo "To check your projects:"
  echo "  sentry-cli projects list --org ${SENTRY_ORG}"
  echo ""
  fail "DSN retrieval failed"
fi

ok "DSN retrieved: ${DIM}${DSN}${RESET}"

# ── 4. Write env files ──────────────────────────────────────────────
REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"

# 4a. Root .env.local (shared between API + web server-side)
ROOT_ENV="${REPO_ROOT}/.env.local"
info "Updating ${ROOT_ENV}..."

# Helper: upsert a KEY=VALUE line in a file
upsert_env() {
  local file="$1" key="$2" value="$3"
  if [[ -f "$file" ]] && grep -q "^${key}=" "$file"; then
    # Replace existing line (macOS sed)
    sed -i '' "s|^${key}=.*|${key}=${value}|" "$file"
  else
    echo "${key}=${value}" >> "$file"
  fi
}

touch "$ROOT_ENV"
upsert_env "$ROOT_ENV" "SENTRY_DSN" "$DSN"
upsert_env "$ROOT_ENV" "NEXT_PUBLIC_SENTRY_DSN" "$DSN"
upsert_env "$ROOT_ENV" "SENTRY_ENVIRONMENT" "development"
upsert_env "$ROOT_ENV" "NEXT_PUBLIC_SENTRY_ENVIRONMENT" "development"
upsert_env "$ROOT_ENV" "SENTRY_ORG" "$SENTRY_ORG"
upsert_env "$ROOT_ENV" "SENTRY_PROJECT" "$SENTRY_PROJECT"

ok "Root .env.local updated"

# 4b. Web source map upload env (used by withSentryConfig at build time)
WEB_SENTRY_ENV="${REPO_ROOT}/apps/web/.env.sentry-build-plugin"
info "Writing ${WEB_SENTRY_ENV}..."

cat > "$WEB_SENTRY_ENV" <<EOF
# Auto-generated by scripts/dev/sentry-setup.sh
# This file is gitignored. Do NOT commit it.
SENTRY_AUTH_TOKEN=${SENTRY_AUTH_TOKEN}
SENTRY_ORG=${SENTRY_ORG}
SENTRY_PROJECT=${SENTRY_PROJECT}
EOF

ok "Web build plugin env written"

# ── 5. Summary ──────────────────────────────────────────────────────
echo ""
echo "┌─────────────────────────────────────────────────────────┐"
echo "│  Sentry setup complete                                  │"
echo "├─────────────────────────────────────────────────────────┤"
echo "│                                                         │"
echo "│  Org:         ${SENTRY_ORG}                             │"
echo "│  Project:     ${SENTRY_PROJECT}                         │"
echo "│  Environment: development                               │"
echo "│  DSN:         (written to .env.local)                   │"
echo "│                                                         │"
echo "│  Env files updated:                                     │"
echo "│    .env.local                                           │"
echo "│    apps/web/.env.sentry-build-plugin                    │"
echo "│                                                         │"
echo "│  For production, set in your CI / Cloud Run env:        │"
echo "│    SENTRY_DSN=<same DSN>                                │"
echo "│    NEXT_PUBLIC_SENTRY_DSN=<same DSN>                    │"
echo "│    SENTRY_ENVIRONMENT=production                        │"
echo "│    SENTRY_AUTH_TOKEN=<build token>                      │"
echo "│    SENTRY_ORG=${SENTRY_ORG}                             │"
echo "│    SENTRY_PROJECT=${SENTRY_PROJECT}                     │"
echo "│                                                         │"
echo "└─────────────────────────────────────────────────────────┘"
echo ""
echo "Restart your dev servers to pick up the new env vars."
